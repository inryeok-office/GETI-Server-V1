-- ============================================================
-- 6. jobs
-- ============================================================
CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    created_by_member_id BIGINT,
    manager_member_id BIGINT,
    type VARCHAR(30) NOT NULL,
    application_method VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    title VARCHAR(500) NOT NULL,
    body_markdown TEXT,
    source_name VARCHAR(255),
    external_job_id VARCHAR(255),
    external_url VARCHAR(2000),
    discord_channel_key VARCHAR(255),
    recruitment_started_at TIMESTAMP,
    recruitment_ended_at TIMESTAMP,
    target_grade INTEGER,
    capacity INTEGER,
    first_come_served BOOLEAN NOT NULL,
    required_skills JSONB,
    application_form_schema JSONB,
    view_count BIGINT NOT NULL,
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    closed_at TIMESTAMP,
    deleted_at TIMESTAMP,
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id)
        REFERENCES companies (id),
    CONSTRAINT fk_jobs_created_by_member FOREIGN KEY (created_by_member_id)
        REFERENCES members (id) ON DELETE SET NULL,
    CONSTRAINT fk_jobs_manager_member FOREIGN KEY (manager_member_id)
        REFERENCES members (id) ON DELETE SET NULL,
    CONSTRAINT ck_jobs_view_count CHECK (view_count >= 0),
    CONSTRAINT ck_jobs_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_jobs_target_grade CHECK (target_grade IS NULL OR target_grade BETWEEN 1 AND 3)
);

CREATE INDEX idx_jobs_company_id ON jobs (company_id);
CREATE INDEX idx_jobs_created_by_member_id ON jobs (created_by_member_id);
CREATE INDEX idx_jobs_manager_member_id ON jobs (manager_member_id);
CREATE INDEX idx_jobs_status ON jobs (status);
CREATE INDEX idx_jobs_status_published_at ON jobs (status, published_at);
-- 외부 수집 공고 중복 방지: source_name/external_job_id가 둘 다 있는 Row만 유일해야 하고
-- 내부 공고(둘 다 NULL)는 여러 개 있어도 된다 -> Partial Unique Index.
CREATE UNIQUE INDEX uk_jobs_source_external_id ON jobs (source_name, external_job_id)
    WHERE source_name IS NOT NULL AND external_job_id IS NOT NULL;

