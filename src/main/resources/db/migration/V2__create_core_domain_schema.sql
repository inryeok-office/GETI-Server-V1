-- GETI 최신 최소 19개 Table 핵심 Domain Schema.
-- 과거 27개 Table 설계는 폐기되었으며 이 Migration에서 복원하지 않는다.
--
-- 이 Source Set(src/main)의 실제 첫 Migration이지만 V1이 아니라 V2로 시작한다.
-- src/integrationTest/resources/db/migration/V1__create_persistence_probe.sql이 이미
-- V1을 사용 중이고, integrationTest 실행 시에는 main과 integrationTest의 resources가
-- 같은 classpath(db/migration)로 합쳐져 Flyway가 두 위치를 구분하지 못한다(Version 충돌).
-- persistence_probe Migration은 이미 병합된 Test 전용 파일이라 수정하지 않고, 대신 이
-- 새 Migration의 Version을 V2로 시작해 충돌을 피한다.
--
-- 생성 순서는 FK 의존성을 따른다. members와 files는 서로를 참조하는 순환 관계라
-- members를 먼저 만들고(profile_image_file_id는 이 시점에 FK 없이 컬럼만 추가),
-- files를 만든 뒤 ALTER TABLE로 members -> files FK를 뒤늦게 추가한다.
--
-- FK 삭제 정책(ON DELETE) 원칙:
--   - 같은 Aggregate에 종속된 자식/연결 Row(member_roles, refresh_tokens,
--     member_job_preferences, job_ai_analyses, recommendations, notifications)는
--     부모가 사라지면 함께 의미를 잃으므로 CASCADE.
--   - 작성자/업로더/승인자처럼 이력 성격이 강하지 않은 Nullable 참조는 SET NULL로
--     레코드 자체는 보존한다(files.uploader_member_id, members.profile_image_file_id,
--     companies.logo_file_id, jobs.created_by_member_id/manager_member_id,
--     inquiries.answered_by_member_id, async_operations.*, audit_logs.actor_member_id).
--   - 지원/신청/제출/문의처럼 보존해야 하는 이력이면서 NOT NULL FK인 경우는 상위
--     Row를 실수로 지우면 이력이 함께 사라지는 것을 막기 위해 명시적 ON DELETE를
--     선언하지 않는다(PostgreSQL 기본값 NO ACTION = 참조가 남아있으면 삭제 차단).

-- ============================================================
-- 1. members
-- ============================================================
CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oauth_provider VARCHAR(30) NOT NULL,
    oauth_subject VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    name VARCHAR(100),
    status VARCHAR(30) NOT NULL,
    academic_status VARCHAR(30),
    cohort INTEGER,
    grade INTEGER,
    department VARCHAR(30),
    profile_image_file_id BIGINT,
    phone_number VARCHAR(30),
    introduction VARCHAR(1000),
    github_url VARCHAR(500),
    profile_public BOOLEAN NOT NULL,
    majors JSONB,
    skills JSONB,
    desired_positions JSONB,
    rejection_reason VARCHAR(1000),
    approved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    withdrawn_at TIMESTAMP,
    CONSTRAINT uk_members_oauth_provider_subject UNIQUE (oauth_provider, oauth_subject),
    CONSTRAINT uk_members_email UNIQUE (email),
    CONSTRAINT ck_members_grade CHECK (grade IS NULL OR grade BETWEEN 1 AND 3)
);

-- ============================================================
-- 2. files
-- ============================================================
CREATE TABLE files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_member_id BIGINT,
    owner_type VARCHAR(100) NOT NULL,
    owner_id BIGINT NOT NULL,
    object_key VARCHAR(1000) NOT NULL,
    original_name VARCHAR(500) NOT NULL,
    content_type VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL,
    contains_personal_information BOOLEAN NOT NULL,
    expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    CONSTRAINT fk_files_uploader_member FOREIGN KEY (uploader_member_id)
        REFERENCES members (id) ON DELETE SET NULL,
    CONSTRAINT ck_files_size_bytes CHECK (size_bytes >= 0)
);

CREATE INDEX idx_files_uploader_member_id ON files (uploader_member_id);
CREATE INDEX idx_files_owner ON files (owner_type, owner_id);

-- members.profile_image_file_id -> files.id (순환 FK, files 생성 이후 추가)
ALTER TABLE members
    ADD CONSTRAINT fk_members_profile_image_file FOREIGN KEY (profile_image_file_id)
        REFERENCES files (id) ON DELETE SET NULL;

